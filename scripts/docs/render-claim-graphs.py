#!/usr/bin/env python3
"""Render the measured-claim SVGs embedded in the E8450 ROM handbook.

No third-party packages are required. Data is intentionally kept beside its
chart definition so reviewers can compare every plotted value with the cited
source. Run with --check to fail when committed SVGs are stale.
"""

from __future__ import annotations

import argparse
import html
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "assets"

INK = "#172033"
MUTED = "#5f6b7a"
GRID = "#d9e1ea"
PANEL = "#ffffff"
PAGE = "#f4f7fb"
BLUE = "#2878b5"
TEAL = "#159a8c"
ORANGE = "#e07a2d"
RED = "#c84a4a"
PURPLE = "#7957b8"
GREEN = "#4a9b55"


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


class SVG:
    def __init__(self, title: str, description: str, height: int = 560):
        self.width = 1000
        self.height = height
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.width} {height}" role="img" aria-labelledby="title desc">',
            f"<title id=\"title\">{esc(title)}</title>",
            f"<desc id=\"desc\">{esc(description)}</desc>",
            '<metadata>Generated by scripts/docs/render-claim-graphs.py</metadata>',
            f'<rect width="1000" height="{height}" rx="18" fill="{PAGE}"/>',
        ]
        self.text(40, 42, title, "title")
        self.text(40, 67, description, "subtitle")

    def text(self, x: float, y: float, value: object, cls: str = "label", anchor: str = "start") -> None:
        styles = {
            "title": (25, 700, INK),
            "subtitle": (14, 400, MUTED),
            "panel-title": (17, 700, INK),
            "label": (14, 400, INK),
            "small": (12, 400, MUTED),
            "value": (14, 700, INK),
        }
        size, weight, fill = styles[cls]
        self.parts.append(
            f'<text x="{x:.1f}" y="{y:.1f}" text-anchor="{anchor}" '
            f'font-family="sans-serif" font-size="{size}" font-weight="{weight}" '
            f'fill="{fill}">{esc(value)}</text>'
        )

    def line(self, x1: float, y1: float, x2: float, y2: float, cls: str = "axis", **attrs: object) -> None:
        stroke = attrs.pop("stroke", GRID if cls == "grid" else "#8d99a8")
        stroke_width = attrs.pop("stroke_width", 1)
        extra = " ".join(f'{k.replace("_", "-")}="{esc(v)}"' for k, v in attrs.items())
        self.parts.append(
            f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            f'stroke="{stroke}" stroke-width="{stroke_width}" {extra}/>'
        )

    def rect(self, x: float, y: float, w: float, h: float, fill: str, rx: float = 0, **attrs: object) -> None:
        extra = " ".join(f'{k.replace("_", "-")}="{esc(v)}"' for k, v in attrs.items())
        self.parts.append(
            f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" rx="{rx}" fill="{fill}" {extra}/>'
        )

    def circle(self, x: float, y: float, r: float, fill: str, **attrs: object) -> None:
        extra = " ".join(f'{k.replace("_", "-")}="{esc(v)}"' for k, v in attrs.items())
        self.parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" fill="{fill}" {extra}/>')

    def panel(self, x: float, y: float, w: float, h: float, title: str) -> None:
        self.rect(x, y, w, h, PANEL, 12, stroke=GRID)
        self.text(x + 20, y + 29, title, "panel-title")

    def finish(self, source: str, note: str | None = None) -> str:
        if note:
            self.text(40, self.height - 38, note, "small")
        self.text(40, self.height - 17, f"Source: {source}", "small")
        self.parts.append("</svg>\n")
        return "\n".join(self.parts)


def vertical_bars(
    svg: SVG,
    x: float,
    y: float,
    w: float,
    h: float,
    labels: list[str],
    values: list[float],
    max_value: float,
    colors: list[str],
    suffix: str,
    ticks: int = 4,
    decimals: int = 1,
) -> None:
    plot_left, plot_right = x + 58, x + w - 18
    plot_top, plot_bottom = y + 50, y + h - 58
    plot_h = plot_bottom - plot_top
    for i in range(ticks + 1):
        value = max_value * i / ticks
        gy = plot_bottom - plot_h * i / ticks
        svg.line(plot_left, gy, plot_right, gy, "grid")
        svg.text(plot_left - 8, gy + 4, f"{value:g}", "small", "end")
    svg.line(plot_left, plot_top, plot_left, plot_bottom)
    svg.line(plot_left, plot_bottom, plot_right, plot_bottom)
    slot = (plot_right - plot_left) / len(values)
    bar_w = min(82, slot * 0.52)
    for i, (label, value, color) in enumerate(zip(labels, values, colors)):
        bx = plot_left + slot * (i + 0.5) - bar_w / 2
        bh = plot_h * value / max_value
        by = plot_bottom - bh
        svg.rect(bx, by, bar_w, bh, color, 5)
        shown = f"{value:.{decimals}f}{suffix}"
        svg.text(bx + bar_w / 2, by - 8, shown, "value", "middle")
        svg.text(bx + bar_w / 2, plot_bottom + 23, label, "small", "middle")


def error_bars(
    svg: SVG,
    x: float,
    y: float,
    w: float,
    h: float,
    labels: list[str],
    means: list[float],
    errors: list[float],
    max_value: float,
    colors: list[str],
    suffix: str,
    decimals: int = 1,
) -> None:
    plot_left, plot_right = x + 48, x + w - 16
    plot_top, plot_bottom = y + 50, y + h - 55
    plot_h = plot_bottom - plot_top
    for i in range(5):
        value = max_value * i / 4
        gy = plot_bottom - plot_h * i / 4
        svg.line(plot_left, gy, plot_right, gy, "grid")
        svg.text(plot_left - 7, gy + 4, f"{value:g}", "small", "end")
    slot = (plot_right - plot_left) / len(means)
    bar_w = min(62, slot * 0.44)
    for i, (label, mean, error, color) in enumerate(zip(labels, means, errors, colors)):
        cx = plot_left + slot * (i + 0.5)
        bh = plot_h * mean / max_value
        svg.rect(cx - bar_w / 2, plot_bottom - bh, bar_w, bh, color, 5)
        high = plot_bottom - plot_h * min(max_value, mean + error) / max_value
        low = plot_bottom - plot_h * max(0, mean - error) / max_value
        svg.line(cx, high, cx, low, "axis", stroke_width=2)
        svg.line(cx - 8, high, cx + 8, high, "axis", stroke_width=2)
        svg.line(cx - 8, low, cx + 8, low, "axis", stroke_width=2)
        svg.text(cx, high - 8, f"{mean:.{decimals}f}±{error:.{decimals}f}{suffix}", "value", "middle")
        svg.text(cx, plot_bottom + 22, label, "small", "middle")


def aqm_latency() -> str:
    svg = SVG(
        "AQM cuts loaded latency while preserving upload rate",
        "Same controlled saturating-upload comparison; exact values from the original A/B.",
    )
    svg.panel(35, 92, 450, 390, "Ping p95 under load (lower is better)")
    vertical_bars(svg, 35, 92, 450, 390, ["AQM off", "AQM on"], [196, 33.8], 210, [RED, TEAL], " ms")
    svg.panel(515, 92, 450, 390, "Upload throughput (higher is better)")
    vertical_bars(svg, 515, 92, 450, 390, ["AQM off", "AQM on"], [8.304, 8.178], 9, [BLUE, TEAL], " Mbit/s", decimals=3)
    return svg.finish(
        "docs/research/qos-aqm-lab-notes.md §22.12",
        "One run per mode in this initial gate; later hardened-AQM testing measured 30.5 ms p95.",
    )


