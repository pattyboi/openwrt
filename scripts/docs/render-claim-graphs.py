def radio_rssi() -> str:
    svg = SVG(
        "Measured signal change after EEPROM calibration",
        "Fixed-position before/after comparisons; farther right is stronger signal.",
        590,
    )
    svg.panel(35, 92, 930, 410, "Received signal strength (dBm)")
    left, right = 230, 925
    min_dbm, max_dbm = -70, -15
    for tick in range(-70, -14, 5):
        x = left + (right - left) * (tick - min_dbm) / (max_dbm - min_dbm)
        svg.line(x, 150, x, 425, "grid")
        svg.text(x, 452, tick, "small", "middle")
    rows = [
        ("5 GHz · S23 far", -65.0, -61.0, "+4.0 dB"),
        ("5 GHz · Pi near", -26.0, -21.0, "+5.0 dB"),
        ("2.4 GHz · Pi near", -22.8, -20.6, "+2.2 dB"),
    ]
    for i, (label, before, after, delta) in enumerate(rows):
        y = 195 + i * 92
        bx = left + (right - left) * (before - min_dbm) / (max_dbm - min_dbm)
        ax = left + (right - left) * (after - min_dbm) / (max_dbm - min_dbm)
        svg.text(left - 15, y + 5, label, "label", "end")
